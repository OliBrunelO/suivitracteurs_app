// Bouton icône générique avec tooltip au survol
export function IconBtn({ onClick, title, color = 'gray', children, className = '' }) {
  const colors = {
    gray:    'text-gray-400 hover:text-gray-700 hover:bg-gray-100',
    primary: 'text-primary-500 hover:text-primary-700 hover:bg-primary-50',
    red:     'text-red-400 hover:text-red-600 hover:bg-red-50',
    amber:   'text-amber-400 hover:text-amber-600 hover:bg-amber-50',
  }
  return (
    <button
      onClick={onClick}
      title={title}
      className={`p-1.5 rounded-lg transition-colors ${colors[color]} ${className}`}
    >
      {children}
    </button>
  )
}
